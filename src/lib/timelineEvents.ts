export function eventToCard(ev: TimelineEvent, index: number): TimelineCard {
  return {
    id: `event:${index}`,
    name: ev.name,
    image_url: null,
    date: { year: ev.year, month: ev.month },
    source: 'event',
    category: ev.category,
    emoji: EVENT_CATEGORY_EMOJI[ev.category],
  };
}

export function allEventCards(): TimelineCard[] {
  return TIMELINE_EVENTS.map(eventToCard);
}
